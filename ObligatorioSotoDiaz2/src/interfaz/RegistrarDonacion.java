    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        Empresa empresa = (Empresa) cmbEmpresa.getSelectedItem();
        double kilos = leerKilos();

        if (empresa == null) {
            mostrarError("Primero debe registrar una empresa");
        } else if (kilos <= 0) {
            mostrarError("Los kilos deben ser un numero mayor a cero");
        } else {
            int tipo = cmbTipo.getSelectedIndex() + 1; // el combo empieza en 0 y los tipos en 1
            Donacion donacion = sistema.registrarDonacion(empresa, tipo, kilos);
            JOptionPane.showMessageDialog(this, "Donacion registrada. Numero: " + donacion.getNumero());
            limpiar();
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    // Devuelve -1 si lo escrito no es un numero valido
    private double leerKilos() {
        double kilos = -1;
        try {
            kilos = Double.parseDouble(txtKilos.getText().trim().replace(',', '.'));
            if (Double.isNaN(kilos) || Double.isInfinite(kilos)) {
                kilos = -1;
            }
        } catch (NumberFormatException e) {
            kilos = -1;
        }
        return kilos;
    }

    private void mostrarError(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Error", JOptionPane.ERROR_MESSAGE);
    }

    private void limpiar() {
        txtKilos.setText("");
        cmbTipo.setSelectedIndex(0);
        txtKilos.requestFocus();
    }


    // Llena el combo con las empresas registradas, manteniendo la elegida si sigue existiendo
    private void cargarEmpresas() {
        Empresa elegida = (Empresa) cmbEmpresa.getSelectedItem();
        cmbEmpresa.removeAllItems();
        for (Empresa e : sistema.getEmpresas()) {
            cmbEmpresa.addItem(e);
        }
        if (elegida != null) {
            cmbEmpresa.setSelectedItem(elegida);
        }
    }

